"""Writes src/jak/types_gen.hpp: the Jak II structures the board reads, as C++ structs.

The fields come from OpenGOAL's deftypes (jak-project, ISC License, Copyright (c) 2020-2026 OpenGOAL
Team), in their order, named as GOAL names them with '-' as '_' and '?' as '_p', so
`(-> self control turn-to-magnitude)` is `self.control.turn_to_magnitude`. Offsets and overlays are
not kept: the port needs the values, not the PS2's layout. A field of a type the port does not use
(a process, a handle, a sound) becomes an opaque placeholder of the right meaning.

    python3 tools/gen_jak_types.py <jak-project checkout> > src/jak/types_gen.hpp
"""
import re
import sys
from pathlib import Path

# (GOAL file, deftype, C++ name, parent C++ name or None)
TYPES = [
    ("goal_src/jak2/engine/physics/dynamics-h.gc", "dynamics", "Dynamics", None),
    ("goal_src/jak2/engine/math/transformq-h.gc", "trsqv", "Trsqv", None),
    ("goal_src/jak2/engine/collide/collide-shape-h.gc", "collide-shape", "CollideShape", "Trsqv"),
    ("goal_src/jak2/engine/collide/collide-shape-h.gc", "collide-shape-moving", "CollideShapeMoving",
     "CollideShape"),
    ("goal_src/jak2/engine/collide/collide-target-h.gc", "control-info", "ControlInfo",
     "CollideShapeMoving"),
    ("goal_src/jak2/engine/target/surface-h.gc", "surface", "Surface", None),
    ("goal_src/jak2/engine/target/board/board-h.gc", "board-info", "BoardInfo", None),
]

# Fields trsqv inherits from trs/trsq, which the generator writes first.
TRS_FIELDS = [("trans", "vector", ""), ("quat", "quaternion", ""), ("scale", "vector", "")]

SCALARS = {
    "float": "float", "meters": "float", "degrees": "float", "seconds": "TimeFrame",
    "time-frame": "TimeFrame", "int64": "int64_t", "uint64": "uint64_t", "int32": "int32_t",
    "uint32": "uint32_t", "int16": "int16_t", "uint16": "uint16_t", "int8": "int8_t",
    "uint8": "uint8_t", "int": "int32_t", "uint": "uint32_t", "symbol": "Symbol",
    "vector": "Vec", "quaternion": "Quat", "matrix": "Mat",
    "pat-surface": "PatSurface", "collide-status": "CollideStatus",
    "surface-flag": "SurfaceFlag", "surface": "Surface*", "cpad-info": "CpadInfo*", "collide-shape-prim": "CollideShapePrim*", "dynamics": "Dynamics*",
    "board-tricks": "BoardTricks", "ground-tween-info": "GroundTweenInfo",
    "collide-spec": "uint32_t", "cshape-reaction-flags": "uint32_t", "penetrate": "uint64_t",
    "nav-flags": "uint8_t",
}


def deftype_block(text, name):
    m = re.search(r"\(deftype " + re.escape(name) + r" \(", text)
    if not m:
        raise SystemExit(f"no deftype {name}")
    i = text.index("((", m.end())
    depth, j = 0, i
    while True:
        c = text[j]
        depth += c == "("
        depth -= c == ")"
        j += 1
        if depth == 0:
            return text[i + 1:j - 1]


def fields(block):
    out = []
    for line in block.splitlines():
        line = line.split(";")[0].strip()
        if not line.startswith("(") or line.startswith("(:"):
            continue
        line = line[1:]
        if line.endswith(")") and line.count("(") < line.count(")"):
            line = line[:-1]
        m = re.match(r"([A-Za-z0-9?!*<>-]+)\s+(\([^)]*\)\)?|[a-z0-9-]+)(.*)$", line)
        if not m:
            continue
        name, ty, rest = m.group(1), m.group(2), m.group(3)
        if ":overlay-at" in rest:
            continue  # an alias of another field
        cm = re.match(r"\s+(\d+)", rest)
        count = cm.group(1) if cm else ""
        if ty.startswith("("):
            ty = "function"
        out.append((name, ty, count))
    return out


def cname(name):
    return name.replace("-", "_").replace("?", "_p").replace("!", "_x")


def ctype(ty):
    return SCALARS.get(ty, "Opaque")


def main():
    root = Path(sys.argv[1])
    print("// SPDX-License-Identifier: MIT AND ISC")
    print("// Generated by tools/gen_jak_types.py from OpenGOAL's deftypes (jak-project, ISC License,")
    print("// Copyright (c) 2020-2026 OpenGOAL Team; THIRD_PARTY.md). Do not edit: run the generator.")
    print("#pragma once\n")
    print('#include "jak/basic_types.hpp"\n')
    print("namespace jak {\n")
    print("struct Surface;\n")
    for path, goal, cpp, parent in TYPES:
        text = (root / path).read_text()
        fl = fields(deftype_block(text, goal))
        if goal == "trsqv":
            fl = TRS_FIELDS + fl
        base = f" : {parent}" if parent else ""
        print(f"// ({goal}), {path.split('goal_src/jak2/')[1]}")
        print(f"struct {cpp}{base} {{")
        seen = set()
        for name, ty, count in fl:
            if name in seen:
                continue
            seen.add(name)
            t = ctype(ty)
            arr = f"[{count}]" if count else ""
            note = "" if t != "Opaque" else f"  // GOAL type {ty}, not used by the port"
            if goal == "surface" and ty == "function":
                t, note = "SurfaceHook", ""
            if goal == "surface" and name == "mult-hook":
                t = "SurfaceMultHook"
            print(f"    {t} {cname(name)}{arr}{{}};{note}")
        print("};\n")
    print("} // namespace jak")


if __name__ == "__main__":
    main()

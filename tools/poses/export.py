"""Writes the secondary-motion channels (CHANNELS below: ears, tail, face) as the mod's table,
src/rac1/anim/ride_poses.inc: each channel's turns, their axes in each joint's own frame. The clips
themselves are tools/poses/clips.py's.

    python3 tools/poses/export.py <levels>/level_01/mobys/moby_0.glb src/rac1/anim/ride_poses.inc
"""
import sys
import numpy as np
from posetool import Rig

Z = np.array([0, 0, 1.0]); X = np.array([1.0, 0, 0]); Y = np.array([0, 1.0, 0])

# Channels of the secondary motion the mod drives on top of the clips (springs, rac1/ride_pose):
# per channel, the joints it turns, each about an axis of his standing pose's model space (x his
# front, y his left, z up) by `degrees` at full value (1). The table turns them into each joint's own
# axis, so the turn follows the joint wherever the pose has put it.
CHANNELS = {
    # ears: up (x) and swept back (z), the tip more than the root
    'ear_l_up': [(41, X, 18), (42, X, 12), (43, X, 8)],
    'ear_r_up': [(44, X, -18), (45, X, -12), (46, X, -8)],
    'ear_l_back': [(41, Z, 16), (42, Z, 10), (43, Z, 8)],
    'ear_r_back': [(44, Z, -16), (45, Z, -10), (46, Z, -8)],
    # tail: to his left (z) and up (y), root and tip apart for a wave
    'tail_side': [(104, Z, 6), (105, Z, 8), (106, Z, 8)],
    'tail_tip': [(107, Z, 10), (108, Z, 12), (109, Z, 12), (110, Z, 12)],
    'tail_up': [(104, Y, -6), (105, Y, -6), (106, Y, -8), (107, Y, -8), (108, Y, -8)],
    # face: jaw open, eyelids shut, brows up, snout curl
    'jaw': [(10, Y, 16)],
    'blink': [(19, Y, 68), (20, Y, 68)],
    'brows': [(26, Y, -16), (30, Y, -16)],
    'snarl': [(9, Y, -10)],
    # the board's upper-body joint-mod (Jak's joint 5): his chest turned about up, a degree a unit
    'upper_twist': [(4, Z, 1.0)],
}

r = Rig(sys.argv[1])
out = ["// SPDX-License-Identifier: MIT", "// Copyright (c) 2026 Mateusz Kłysz",
       "// Ratchet's secondary-motion channels: joint turns in each joint's own frame (seq 0).",
       "// Generated by tools/poses/export.py; do not edit by hand.", "#pragma once", "",
       '#include "rac1/anim/ride_pose.hpp"', "", "namespace rac1::poses {", ""]
# The secondary-motion channels: each turn's axis in the joint's own frame (standing pose).
rot, tr = r.local_pose(0, 0)
G = r.globals(rot, tr)
for n, turns in CHANNELS.items():
    out.append(f"constexpr ChannelTurn c_{n}[] = {{")
    for j, axis, deg in turns:
        a = np.asarray(axis, float); a = a / np.linalg.norm(a)
        loc = G[j][:3, :3].T @ a
        out.append(f"    {{{j}, {{{loc[0]:.5f}f, {loc[1]:.5f}f, {loc[2]:.5f}f}}, {deg:.1f}f}},")
    out.append("};")
out.append("")
out.append("// Channels, in the order of rac1::Channel.")
out.append("constexpr Chan kChannels[] = {")
for n in CHANNELS:
    out.append(f"    {{c_{n}, sizeof(c_{n}) / sizeof(c_{n}[0])}},  // {n}")
out.append("};")
out.append("")
out.append("} // namespace rac1::poses")
open(sys.argv[2], 'w').write("\n".join(out) + "\n")
print(list(CHANNELS))

"""RAC-Board's riding clips for Ratchet: one per animation the board's logic plays, with Jak II's
name and number of frames (src/board/anim_table.cpp), so the logic's frame numbers, seeks and blends
drive them as they drive Jak's.

A clip is keyframes (tools/poses/ride_keys.json): at each key, every joint's turn over his standing
pose (x, y, z, w), the hips' move, and the board's turn (x, y, z, w) and place (model units: x his
heading, y left, z up). Between keys a Catmull-Rom curve. This writes the mod's table:

    python3 tools/poses/clips.py src/rac1/ride_clips.inc
"""
import json, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
KEYS = os.path.join(HERE, 'ride_keys.json')


def curve(keys, vals, n):
    """Catmull-Rom through (keys[i], vals[i]) sampled at frames 0..n-1 (vals: (k, ...) array)."""
    vals = np.asarray(vals, float)
    out = np.empty((n,) + vals.shape[1:])
    if len(keys) == 1:
        out[:] = vals[0]
        return out
    ks = [2 * keys[0] - keys[1]] + list(keys) + [2 * keys[-1] - keys[-2]]
    vs = np.concatenate([vals[:1], vals, vals[-1:]])
    i = 1
    for f in range(n):
        while i < len(ks) - 3 and f > ks[i + 1]:
            i += 1
        span = ks[i + 1] - ks[i]
        u = min(1.0, max(0.0, (f - ks[i]) / span))
        m1 = (vs[i + 1] - vs[i - 1]) / (ks[i + 1] - ks[i - 1]) * span
        m2 = (vs[i + 2] - vs[i]) / (ks[i + 2] - ks[i]) * span
        u2, u3 = u * u, u * u * u
        out[f] = ((2 * u3 - 3 * u2 + 1) * vs[i] + (u3 - 2 * u2 + u) * m1 + (-2 * u3 + 3 * u2) * vs[i + 1]
                  + (u3 - u2) * m2)
    return out


def unit(q):
    return q / np.linalg.norm(q, axis=-1, keepdims=True)


def frames(clip):
    """Per frame: joint turns (n, joints, 4), hips (n, 3), board turn (n, 4), board place (n, 3)."""
    n, k = clip['frames'], clip['keys']
    q = unit(curve(k, clip['q'], n))
    return q, curve(k, clip['hips'], n), unit(curve(k, clip['bq'], n)), curve(k, clip['bp'], n)


def export(path, keys=KEYS):
    clips = json.load(open(keys))
    out = ["// SPDX-License-Identifier: MIT", "// Copyright (c) 2026 Mateusz Kłysz",
           "// Ratchet's riding clips, named and timed as Jak II's board animations.",
           "// Generated by tools/poses/clips.py from tools/poses/ride_keys.json; do not edit by hand.",
           "#pragma once", "", '#include "rac1/ride_clip.hpp"', "", "namespace rac1::clips {", ""]
    entries = []
    fl = lambda xs: ", ".join(f"{x:.4f}f" for x in np.ravel(xs))
    for i, (name, c) in enumerate(clips.items()):
        q, hips, bq, bp = frames(c)
        out += [f"// {name}", f"constexpr uint8_t j{i}[] = {{{', '.join(str(j) for j in c['joints'])}}};",
                f"constexpr float q{i}[] = {{{fl(q)}}};", f"constexpr float h{i}[] = {{{fl(hips)}}};",
                f"constexpr float b{i}[] = {{{fl(np.c_[bq, bp])}}};", ""]
        entries.append(f'    {{"{name}-ja", {c["frames"]}, {len(c["joints"])}, j{i}, q{i}, h{i}, b{i}}},')
    out += ["constexpr Clip kClips[] = {"] + entries + ["};", "", "} // namespace rac1::clips"]
    open(path, 'w').write("\n".join(out) + "\n")


if __name__ == "__main__":
    export(*sys.argv[1:3])
